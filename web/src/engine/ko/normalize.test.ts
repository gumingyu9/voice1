import { test } from 'node:test';
import assert from 'node:assert/strict';
import { normalizeKorean, MAX_INPUT_CHARS } from './normalize.ts';

type Case = [input: string, expected: string];

function table(name: string, cases: Case[]): void {
  for (const [input, expected] of cases) {
    test(`${name}: ${JSON.stringify(input)} -> ${JSON.stringify(expected)}`, () => {
      assert.equal(normalizeKorean(input), expected);
    });
  }
}

test('MAX_INPUT_CHARS is 50 and not enforced', () => {
  assert.equal(MAX_INPUT_CHARS, 50);
  const long = '가'.repeat(120);
  assert.equal(normalizeKorean(long), long);
});

