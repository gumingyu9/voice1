test('output contains only Hangul, spaces and . , ? !', () => {
  const samples = [
    'Hello, World! 123 @#$ 😀 안녕~',
    '１２３ ＡＢＣ',
    '가격: $1,234.56 (세금 포함)',
    'a\nb\tc',
    '-5% & 3.14 / 2',
  ];
  for (const sample of samples) {
    assert.match(normalizeKorean(sample), /^[가-힣 .,?!]*$/);
  }
});

test('full-width digits and letters are normalized', () => {
  assert.equal(normalizeKorean('１２３'), '백이십삼');
  assert.equal(normalizeKorean('ＡＢ'), '에이비');
});

test('is idempotent on its own output', () => {
  const once = normalizeKorean('사과 3개, 15,000원! ABC~ 010-1234');
  assert.equal(normalizeKorean(once), once);
});
